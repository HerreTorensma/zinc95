void gfx_draw_circle(surface_t surf, point_t pos, int radius, color_t color) {
	int x = pos.x;
	int y = pos.y;
	
	// Initial 4 points
	surf_set_pixel(surf, x + radius, y, color);
	surf_set_pixel(surf, x - radius, y, color);
	surf_set_pixel(surf, x, y + radius, color);
	surf_set_pixel(surf, x, y - radius, color);

	int x_offset = radius;
	int y_offset = 0;

	int d = 1 - radius;

	while (x_offset > y_offset) {
		y_offset++;
		
		if (d <= 0) {
			d = d + 2 * y_offset + 1;
		} else {
			x_offset--;
			d = d + 2 * (y_offset - x_offset) + 1;
		}
		
		if (x_offset < y_offset) {
			break;
		}

		surf_set_pixel(surf, x + x_offset, y + y_offset, color);
		surf_set_pixel(surf, x - x_offset, y + y_offset, color);
		surf_set_pixel(surf, x + x_offset, y - y_offset, color);
		surf_set_pixel(surf, x - x_offset, y - y_offset, color);

		if (x_offset != y_offset) {
			surf_set_pixel(surf, x + y_offset, y + x_offset, color);
			surf_set_pixel(surf, x - y_offset, y + x_offset, color);
			surf_set_pixel(surf, x + y_offset, y - x_offset, color);
			surf_set_pixel(surf, x - y_offset, y - x_offset, color);
		}
	}
}

// This function is taken from https://zingl.github.io/bresenham.html
void gfx_draw_ellipse(surface_t surf, rect_t bound, color_t color) {
	int x0 = rect_topleft(bound).x;
	int y0 = rect_topleft(bound).y;
	int x1 = rect_bottomright(bound).x;
	int y1 = rect_bottomright(bound).y;

	int a = abs(x1-x0), b = abs(y1-y0), b1 = b&1; /* values of diameter */
	long dx = 4*(1-a)*b*b, dy = 4*(b1+1)*a*a; /* error increment */
	long err = dx+dy+b1*a*a, e2; /* error of 1.step */

	if (x0 > x1) { x0 = x1; x1 += a; } /* if called with swapped points */
	if (y0 > y1) y0 = y1; /* .. exchange them */
	y0 += (b+1)/2; y1 = y0-b1; /* starting pixel */
	a *= 8*a; b1 = 8*b*b;

	do {
		surf_set_pixel(surf, x1, y0, color); /*   I. Quadrant */
		surf_set_pixel(surf, x0, y0, color); /*  II. Quadrant */
		surf_set_pixel(surf, x0, y1, color); /* III. Quadrant */
		surf_set_pixel(surf, x1, y1, color); /*  IV. Quadrant */
		e2 = 2*err;
		if (e2 <= dy) { y0++; y1--; err += dy += a; }  /* y step */ 
		if (e2 >= dx || 2*err > dy) { x0++; x1--; err += dx += b1; } /* x step */
	} while (x0 <= x1);
	
	while (y0-y1 < b) { /* too early stop of flat ellipses a=1 */
		surf_set_pixel(surf, x0-1, y0, color); /* -> finish tip of ellipse */
		surf_set_pixel(surf, x1+1, y0++, color); 
		surf_set_pixel(surf, x0-1, y1, color);
		surf_set_pixel(surf, x1+1, y1--, color); 
	}
}

// This function was generated by ChatGPT based on the previous function
void gfx_draw_filled_ellipse(surface_t surf, rect_t bound, color_t color) {
	int x0 = rect_topleft(bound).x;
	int y0 = rect_topleft(bound).y;
	int x1 = rect_bottomright(bound).x;
	int y1 = rect_bottomright(bound).y;

	int a = abs(x1 - x0);
	int b = abs(y1 - y0);
	int b1 = b & 1;

	long dx = 4 * (1 - a) * b * b;
	long dy = 4 * (b1 + 1) * a * a;
	long err = dx + dy + b1 * a * a;
	long e2;

	if (x0 > x1) {
		x0 = x1;
		x1 += a;
	}

	if (y0 > y1)
		y0 = y1;

	y0 += (b + 1) / 2;
	y1 = y0 - b1;

	a *= 8 * a;
	b1 = 8 * b * b;

	do {
		// Fill horizontal spans instead of edge pixels
		for (int x = x0; x <= x1; x++) {
			surf_set_pixel(surf, x, y0, color);
			surf_set_pixel(surf, x, y1, color);
		}

		e2 = 2 * err;

		if (e2 <= dy) {
			y0++;
			y1--;
			err += dy += a;
		}

		if (e2 >= dx || 2 * err > dy) {
			x0++;
			x1--;
			err += dx += b1;
		}

	} while (x0 <= x1);

	while (y0 - y1 < b) {
		for (int x = x0 - 1; x <= x1 + 1; x++) {
			surf_set_pixel(surf, x, y0, color);
			surf_set_pixel(surf, x, y1, color);
		}

		y0++;
		y1--;
	}
}

color_t gfx_spritesheet_get_pixel(spritesheet_t *spritesheet, point_t point) {
	// TODO: clip the wanted rect instead of this check ???
	if (point_in_rect(point, RECT(0, 0, SPRITESHEET_WIDTH, SPRITESHEET_HEIGHT))) {
		return spritesheet->data[point.y * SPRITESHEET_WIDTH + point.x];
	}
	// TODO: should this be 0 or COLOR_NONE ???
	return COLOR_NONE;
}

void gfx_spritesheet_set_pixel(spritesheet_t *spritesheet, point_t point, color_t color) {
	if (point_in_rect(point, RECT(0, 0, SPRITESHEET_WIDTH, SPRITESHEET_HEIGHT))) {
		spritesheet->data[point.y * SPRITESHEET_WIDTH + point.x] = color;
	}
}

rect_t sprite_index_to_spritesheet_rect(int sprite_index, int w, int h) {
	rect_t rect = {
		.x = (sprite_index % SPRITES_PER_ROW) * SPRITE_WIDTH,
		.y = (sprite_index / SPRITES_PER_ROW) * SPRITE_HEIGHT,
		.w = w * SPRITE_WIDTH,
		.h = h * SPRITE_HEIGHT,
	};

	return rect;
}

