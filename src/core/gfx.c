void gfx_draw_map(ram_t *ram, int layer_index, point_t pos, rect_t section, float scale, color_t color_key, rect_t clip_rect, uint32_t mask) {
	section = rect_clip(RECT(0, 0, MAP_WIDTH, MAP_HEIGHT), section);

	for (int i = section.y; i < section.y + section.h; i++) {
		for (int j = section.x; j < section.x + section.w; j++) {
			// TODO: if an empty sprite is drawn, one blue pixel should be drawn like in PICO-8
			// that's to signify it's not sprite 0
			// also erasing should be a thing
			// or maybe placing anything in the map editor while the top left origin of the in frame rect in sprites is 0, 0 will result in all sprites placed being 0??? idk

			int sprite_index = ram->map.layers[layer_index].data[i * MAP_WIDTH + j];
			if (mask != 0b11111111111111111111111111111111 && (ram->sprites[sprite_index].flags & mask) == 0) {
				continue;
			}

			rect_t source_rect = sprite_index_to_spritesheet_rect(sprite_index, 1, 1);

			int scaled_sprite_width = (int)(SPRITE_WIDTH * scale);
			int scaled_sprite_height = (int)(SPRITE_HEIGHT * scale);
			
			rect_t dest_rect = RECT(
				pos.x + j * scaled_sprite_width,
				pos.y + i * scaled_sprite_height,
				scaled_sprite_width,
				scaled_sprite_height
			);

			// TODO: not sure about the performance implications of just passing the clip rect to the spritesheet function
			// because now its still trying to draw each tile and ideally tiles should be culled beforehand
			// but I think until it gives problems this is alright
			gfx_draw_spritesheet_pro(ram, source_rect, dest_rect, color_key, clip_rect);
		}
	}
}

ARRAY_DEFINE(point_t);
void gfx_flood_fill(surface_t surface, point_t point, color_t color, rect_t limit) {
	color_t start_color = surf_get_pixel(surface, point.x, point.y);

	if (color == start_color) {
		return;
	}

	point_t directions[] = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};

	point_t_array_t stack = {0};
	array_init(&stack, get_heap_allocator());

	array_push(&stack, point);

	while (stack.len > 0) {
		point_t current = array_pop(&stack);

		if (point_in_rect(current, limit)) {
			surf_set_pixel(surface, current.x, current.y, color);
		}

		// Iterate directions
		for (int i = 0; i < 4; i++) {
			point_t new_point = {
				current.x + directions[i].x,
				current.y + directions[i].y,
			};

			if (point_in_rect(new_point, limit) && surf_get_pixel(surface, new_point.x, new_point.y) == start_color) {
				surf_set_pixel(surface, new_point.x, new_point.y, color);
				
				array_push(&stack, new_point);
			}
		}
	}

	array_deinit(&stack);
}

